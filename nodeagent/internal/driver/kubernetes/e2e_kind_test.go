// Environment, supplied by e2e-kind.sh.
//
//	PROTEOS_E2E_AGENT_URL    https://127.0.0.1:<port> (a kubectl port-forward)
//	PROTEOS_E2E_AGENT_TOKEN  the shared bearer token
//	PROTEOS_E2E_GUEST_IMAGE  the guest image loaded into the kind node
const (
	envAgentURL   = "PROTEOS_E2E_AGENT_URL"
	envAgentToken = "PROTEOS_E2E_AGENT_TOKEN"
	envGuestImage = "PROTEOS_E2E_GUEST_IMAGE"
)

// bootTimeout is generous: a real pod has to be scheduled, its PVC bound and its
// image unpacked before the guest-agent answers /healthz.
const bootTimeout = 3 * time.Minute

type agent struct {
	url    string
	token  string
	image  string
	client *http.Client
}

func newAgent(t *testing.T) *agent {
	t.Helper()
	base := os.Getenv(envAgentURL)
	token := os.Getenv(envAgentToken)
	if base == "" || token == "" {
		t.Fatalf("%s and %s must be set (run deploy/kubernetes/e2e-kind.sh)", envAgentURL, envAgentToken)
	}
	image := os.Getenv(envGuestImage)
	if image == "" {
		image = "proteos-guest:e2e"
	}
	return &agent{
		url:   strings.TrimSuffix(base, "/"),
		token: token,
		image: image,
		client: &http.Client{
			Timeout: 30 * time.Second,
			// The agent serves a self-signed cert generated by the script. The
			// production control plane pins a CA instead (PROTEOS_NODE_CA_FILE);
			// what is under test here is that TLS is on and the wiring works.
			Transport: &http.Transport{TLSClientConfig: &tls.Config{InsecureSkipVerify: true}},
		},
	}
}

func (a *agent) do(t *testing.T, method, path string, body any) *http.Response {
	t.Helper()
	var rdr io.Reader = http.NoBody
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			t.Fatal(err)
		}
		rdr = bytes.NewReader(b)
	}
	req, err := http.NewRequest(method, a.url+path, rdr)
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set(api.AuthHeader, api.BearerPrefix+a.token)
	resp, err := a.client.Do(req)
	if err != nil {
		t.Fatalf("%s %s: %v", method, path, err)
	}
	return resp
}

func (a *agent) ensure(t *testing.T, id string) {
	t.Helper()
	resp := a.do(t, http.MethodPut, "/v1/machines/"+id, api.EnsureRequest{
		Vcpus: 1, MemMiB: 1024, ImageRef: a.image, DiskID: "disk-" + id, DiskMiB: 1024,
	})
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusAccepted {
		b, _ := io.ReadAll(resp.Body)
		t.Fatalf("ensure: want 202, got %d: %s", resp.StatusCode, b)
	}
}

func (a *agent) status(t *testing.T, id string) (api.MachineStatus, int) {
	t.Helper()
	resp := a.do(t, http.MethodGet, "/v1/machines/"+id, nil)
	defer resp.Body.Close()
	var st api.MachineStatus
	if resp.StatusCode == http.StatusOK {
		if err := json.NewDecoder(resp.Body).Decode(&st); err != nil {
			t.Fatalf("decode status: %v", err)
		}
	}
	return st, resp.StatusCode
}

// waitState polls until the machine reaches want. On failure it prints the last
// status AND reason, which for this backend carries the kubelet's own
// explanation (ImagePullBackOff, Insufficient cpu, ...) — the thing you actually
// need when a pod will not start.
func (a *agent) waitState(t *testing.T, id, want string, timeout time.Duration) api.MachineStatus {
	t.Helper()
	deadline := time.Now().Add(timeout)
	var last api.MachineStatus
	for time.Now().Before(deadline) {
		st, code := a.status(t, id)
		if code == http.StatusOK {
			last = st
			if st.State == want {
				return st
			}
			if st.State == api.StateError && want != api.StateError {
				t.Fatalf("machine %s went to error while waiting for %q: %s", id, want, st.Reason)
			}
		}
		time.Sleep(2 * time.Second)
	}
	t.Fatalf("machine %s never reached %q in %s (last state %q, reason %q)",
		id, want, timeout, last.State, last.Reason)
	return last
}

func (a *agent) destroy(t *testing.T, id string) {
	t.Helper()
	resp := a.do(t, http.MethodDelete, "/v1/machines/"+id, nil)
	resp.Body.Close()
}

// cleanup destroys the machine when the test passed, and deliberately LEAVES IT
// when the test failed. A pod that never became ready is the only evidence of
// why, and destroying it means e2e-kind.sh's dump — pods, describe, events —
// prints nothing at all. The script only checks for leaked objects on a passing
// run, so a machine left behind here never masquerades as a Destroy bug.
func (a *agent) cleanup(t *testing.T, id string) {
	t.Cleanup(func() {
		if t.Failed() {
			t.Logf("test failed: leaving machine %s in the cluster for the post-mortem dump", id)
			return
		}
		a.destroy(t, id)
	})
}

// dialGuest opens the guest tunnel and returns the raw connection. This is the
// same Upgrade the control-plane gateway performs; on 101 the connection becomes
// an opaque byte stream to the machine's guest-agent, which here means a TCP
// connection the cluster-agent made to the pod IP.
func (a *agent) dialGuest(t *testing.T, id string, port uint32) net.Conn {
	t.Helper()
	conn, err := a.tryDialGuest(id, port)
	if err != nil {
		t.Fatalf("dial guest: %v", err)
	}
	return conn
}

// tryDialGuest is dialGuest for callers that expect a refusal and want to retry
// rather than fail — the ssh port is not servable until the sshd sidecar is
// ready, which is a state a machine legitimately passes through.
func (a *agent) tryDialGuest(id string, port uint32) (net.Conn, error) {
	u, err := url.Parse(a.url)
	if err != nil {
		return nil, err
	}
	conn, err := tls.Dial("tcp", u.Host, &tls.Config{InsecureSkipVerify: true})
	if err != nil {
		return nil, fmt.Errorf("dial agent: %w", err)
	}
	path := fmt.Sprintf("/v1/machines/%s/guest?%s=%d", id, api.GuestPortParam, port)
	req := "GET " + path + " HTTP/1.1\r\n" +
		"Host: " + u.Host + "\r\n" +
		api.AuthHeader + ": " + api.BearerPrefix + a.token + "\r\n" +
		"Connection: Upgrade\r\n" +
		"Upgrade: " + api.UpgradeGuestProto + "\r\n\r\n"
	if _, err := conn.Write([]byte(req)); err != nil {
		conn.Close()
		return nil, fmt.Errorf("write upgrade: %w", err)
	}
	br := bufio.NewReader(conn)
	resp, err := http.ReadResponse(br, nil)
	if err != nil {
		conn.Close()
		return nil, fmt.Errorf("read upgrade response: %w", err)
	}
	if resp.StatusCode != http.StatusSwitchingProtocols {
		b, _ := io.ReadAll(resp.Body)
		conn.Close()
		return nil, fmt.Errorf("guest tunnel: want 101, got %d: %s", resp.StatusCode, b)
	}
	if br.Buffered() > 0 {
		// The agent writes nothing after the 101 before piping, so anything
		// buffered would mean the framing assumption is wrong.
		conn.Close()
		return nil, fmt.Errorf("unexpected %d bytes buffered after the 101", br.Buffered())
	}
	return conn, nil
}

// terminal opens a PTY session over the tunnel and returns it plus the tunnel to
// close. It consumes the guest's `hello` text frame so the caller reads only
// PTY output.
func (a *agent) terminal(t *testing.T, id, session string) (*wsclient.Conn, net.Conn) {
	t.Helper()
	tunnel := a.dialGuest(t, id, api.GuestTerminalPort)
	_ = tunnel.SetDeadline(time.Now().Add(30 * time.Second))
	ws, err := wsclient.Dial(tunnel, "guest", "/terminal?session="+session)
	if err != nil {
		tunnel.Close()
		t.Fatalf("terminal ws handshake: %v", err)
	}
	_ = ws.SetDeadline(time.Now().Add(60 * time.Second))
	if _, isText, err := ws.Read(); err != nil || !isText {
		tunnel.Close()
		t.Fatalf("terminal hello: isText=%v err=%v", isText, err)
	}
	return ws, tunnel
}

// echoMarker returns a shell fragment printing marker, written so that the
// marker does NOT appear literally in the command text.
//
// A PTY echoes what is typed into it, so a command containing its own marker
// matches against the echo of the command rather than its output: the assertion
// passes before the command has run, and every later assertion reads a buffer
// that never contained a result. The empty ” splits the token for the reader
// and the matcher while the shell still prints it whole.
func echoMarker(marker string) string {
	return "echo " + marker[:1] + "''" + marker[1:]
}

// runInGuest sends a command to a PTY session and waits for a marker it echoes,
// so the assertion is on the command having actually completed rather than on a
// timer.
func runInGuest(t *testing.T, ws *wsclient.Conn, cmd, marker string, timeout time.Duration) string {
	t.Helper()
	if err := ws.WriteBinary([]byte(cmd + "\n")); err != nil {
		t.Fatalf("write command: %v", err)
	}
	_ = ws.SetDeadline(time.Now().Add(timeout))
	var acc strings.Builder
	for {
		payload, isText, err := ws.Read()
		if err != nil {
			t.Fatalf("reading for %q: %v (got so far: %q)", marker, err, tail(acc.String()))
		}
		if isText {
			continue // control frames, not PTY output
		}
		acc.Write(payload)
		if strings.Contains(acc.String(), marker) {
			return acc.String()
		}
	}
}

func tail(s string) string {
	if len(s) > 500 {
		return "…" + s[len(s)-500:]
	}
	return s
}

// TestKindLifecycle is the whole point of the job: one machine, driven through
// the lifecycle the control plane drives, against a real cluster.
func TestKindLifecycle(t *testing.T) {
	a := newAgent(t)
	const id = "e2e0kind-0000-4000-8000-000000000001"
	a.cleanup(t, id)

	// A machine that has never existed is a 404, not an empty status.
	if _, code := a.status(t, id); code != http.StatusNotFound {
		t.Fatalf("status before create: want 404, got %d", code)
	}

	// Create. This is where a real cluster earns its keep: the pod has to be
	// scheduled, its PVC bound by a provisioner, its image unpacked, and its
	// readiness probe answered THROUGH the NetworkPolicy before the driver will
	// call it running.
	a.ensure(t, id)
	st := a.waitState(t, id, api.StateRunning, bootTimeout)
	if st.GuestIP == "" {
		t.Error("running machine has no pod IP")
	}
	if st.Boot != api.BootCold || st.Snapshot.Present {
		t.Errorf("want a cold boot with no snapshot, got boot=%q snapshot=%v", st.Boot, st.Snapshot.Present)
	}
	if !strings.HasPrefix(st.Handle, "k8s:") {
		t.Errorf("handle = %q, want a k8s: handle", st.Handle)
	}

	// The tunnel: agent → pod IP → guest-agent, and a real PTY at the end of it.
	ws, tunnel := a.terminal(t, id, "e2e")
	out := runInGuest(t, ws, "id -un && "+echoMarker("READY-MARKER"), "READY-MARKER", 60*time.Second)
	if !strings.Contains(out, "dev") {
		t.Errorf("session does not run as the unprivileged `dev` user; got %q", tail(out))
	}

	// Write into the workspace, so the next phase can prove the volume survived.
	runInGuest(t, ws,
		`echo persisted-by-e2e > "$PROTEOS_WORKSPACE/marker.txt" && sync && `+echoMarker("WROTE-MARKER"),
		"WROTE-MARKER", 60*time.Second)
	ws.Close()
	tunnel.Close()

	// Stop. Hibernate is what the control plane sends today; on this backend it
	// is a poweroff that keeps the volume, and it must not claim a snapshot.
	resp := a.do(t, http.MethodPost, "/v1/machines/"+id+"/stop", api.StopRequest{Mode: api.StopModeHibernate})
	if resp.StatusCode != http.StatusAccepted {
		t.Fatalf("stop: want 202, got %d", resp.StatusCode)
	}
	resp.Body.Close()

	st = a.waitState(t, id, api.StateStopped, 2*time.Minute)
	if st.Snapshot.Present {
		t.Error("stop claimed a snapshot this backend cannot take")
	}
	if st.DiskID != "disk-"+id {
		t.Errorf("stopped machine lost its disk id: %q", st.DiskID)
	}

	// Start again and read the marker back. This is the assertion that the PVC
	// is real: a fresh pod, a fresh container filesystem, the same volume.
	a.ensure(t, id)
	a.waitState(t, id, api.StateRunning, bootTimeout)

	ws, tunnel = a.terminal(t, id, "e2e-after-restart")
	defer tunnel.Close()
	defer ws.Close()
	out = runInGuest(t, ws,
		`cat "$PROTEOS_WORKSPACE/marker.txt"; `+echoMarker("READ-MARKER"), "READ-MARKER", 60*time.Second)
	if !strings.Contains(out, "persisted-by-e2e") {
		t.Errorf("the workspace did not survive a stop/start — the PVC is not doing its job; got %q", tail(out))
	}

	// Destroy takes the pod, the volume and the policy with it.
	resp = a.do(t, http.MethodDelete, "/v1/machines/"+id, nil)
	if resp.StatusCode != http.StatusNoContent {
		t.Fatalf("destroy: want 204, got %d", resp.StatusCode)
	}
	resp.Body.Close()
	if _, code := a.status(t, id); code != http.StatusNotFound {
		t.Fatalf("status after destroy: want 404, got %d", code)
	}
}

// TestKindPreviewForward proves the preview path end to end against a real pod:
// the node-agent writes the one-line port preamble into the tunnel and the
// guest's forwarder bridges it to a loopback port inside the container.
func TestKindPreviewForward(t *testing.T) {
	a := newAgent(t)
	const id = "e2e0kind-0000-4000-8000-000000000002"
	a.cleanup(t, id)

	a.ensure(t, id)
	a.waitState(t, id, api.StateRunning, bootTimeout)

	ws, tunnel := a.terminal(t, id, "preview")
	defer tunnel.Close()
	defer ws.Close()

	// A trivial in-guest server on 8080, backgrounded so the PTY stays usable.
	runInGuest(t, ws,
		`nohup node -e "require('http').createServer((q,s)=>s.end('preview-ok')).listen(8080,'127.0.0.1')" `+
			`>/tmp/preview.log 2>&1 & `+echoMarker("STARTED-PREVIEW"),
		"STARTED-PREVIEW", 60*time.Second)
	runInGuest(t, ws,
		`for i in $(seq 1 40); do (exec 3<>/dev/tcp/127.0.0.1/8080) 2>/dev/null && break; sleep 0.5; done; `+echoMarker("PREVIEW-LISTENING"),
		"PREVIEW-LISTENING", 60*time.Second)

	conn := a.dialGuest(t, id, 8080)
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(30 * time.Second))
	if _, err := conn.Write([]byte("GET / HTTP/1.0\r\nHost: preview\r\n\r\n")); err != nil {
		t.Fatalf("write preview request: %v", err)
	}
	body, err := io.ReadAll(conn)
	if err != nil && len(body) == 0 {
		t.Fatalf("read preview response: %v", err)
	}
	if !strings.Contains(string(body), "preview-ok") {
		t.Errorf("preview did not reach the in-guest server; got %q", tail(string(body)))
	}
}

// TestKindSSH proves the K4 sshd sidecar end to end: that sshd is running beside
// the guest, that the guest agent's forward reaches it over the pod's loopback,
// that a key placed where the control plane's injector puts it actually
// authenticates, and that the machine keeps its host identity across a restart.
//
// The three-way home alignment is the subtle part and is asserted directly.
// sshd reads $HOME and AuthorizedKeysFile from the passwd entry; the guest agent
// starts sessions in the PERSISTED home and the injector writes there. If those
// drift apart, ssh authenticates against a file nothing ever writes — and every
// other assertion in this test would still pass.
func TestKindSSH(t *testing.T) {
	a := newAgent(t)
	const id = "e2e0kind-0000-4000-8000-000000000005"
	a.cleanup(t, id)

	a.ensure(t, id)
	a.waitState(t, id, api.StateRunning, bootTimeout)

	// 1. sshd answers through the tunnel. The forward is the only route in:
	// sshd binds the pod's loopback, which nothing outside the pod can address.
	//
	// Retried, because a machine is RUNNING as soon as its guest container is
	// ready and sshd is ready a little later on a first boot — it generates the
	// machine's host keys. That ordering is deliberate (a broken sshd must not
	// cost a user their terminal), so the driver refuses an ssh dial until sshd
	// is ready rather than handing back a connection that closes. Waiting here
	// is what a client does; asserting on the first attempt would be asserting
	// the opposite design.
	banner := waitForSSHBanner(t, a, id, 90*time.Second)
	if !strings.HasPrefix(banner, "SSH-2.0-") {
		t.Fatalf("guest port %d is not sshd; got %q", api.GuestSSHPort, banner)
	}

	ws, tunnel := a.terminal(t, id, "ssh")
	defer tunnel.Close()
	defer ws.Close()

	// 2. The homes agree, and they are on the volume.
	out := runInGuest(t, ws,
		`echo "home=$HOME passwd=$(getent passwd dev | cut -d: -f6)"; `+echoMarker("HOME-CHECK"),
		"HOME-CHECK", 60*time.Second)
	if !strings.Contains(out, "home=/persist/home passwd=/persist/home") {
		t.Fatalf("the session home and the passwd home disagree, so sshd would read authorized_keys "+
			"from a directory nothing writes: %q", tail(out))
	}

	// 3. A key where the injector puts it authenticates. Generated in-guest so
	// the private half never leaves the machine, and used from the guest
	// container against the sidecar's loopback sshd — the same daemon the
	// tunnel reached above.
	runInGuest(t, ws,
		`ssh-keygen -q -t ed25519 -f /tmp/e2e_key -N "" && mkdir -p "$HOME/.ssh" && chmod 700 "$HOME/.ssh" && `+
			`cat /tmp/e2e_key.pub > "$HOME/.ssh/authorized_keys" && chmod 600 "$HOME/.ssh/authorized_keys" && `+
			echoMarker("KEY-INSTALLED"),
		"KEY-INSTALLED", 60*time.Second)

	out = runInGuest(t, ws,
		`ssh -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o BatchMode=yes `+
			`-i /tmp/e2e_key dev@127.0.0.1 "id -un; pwd" >/tmp/ssh.out 2>/tmp/ssh.err; echo "rc=$?"; `+
			`cat /tmp/ssh.out /tmp/ssh.err; `+echoMarker("SSH-DONE"),
		"SSH-DONE", 90*time.Second)
	if !strings.Contains(out, "rc=0") {
		t.Fatalf("ssh login failed: %q", tail(out))
	}
	// The session lands as the unprivileged user, in the home that survives.
	if !strings.Contains(out, "dev") || !strings.Contains(out, "/persist/home") {
		t.Errorf("ssh session is not the `dev` user in the persisted home: %q", tail(out))
	}

	// 4. The host identity is the machine's, not the image's, and it survives.
	// Take the fingerprint sshd presents, restart the machine, take it again: an
	// image-baked key would make every machine identical, and an ephemeral one
	// would change here and greet the user with a host-key warning on every
	// boot. A stable fingerprint across a fresh container is also the only
	// evidence that the keys are really on the volume.
	out = runInGuest(t, ws, hostKeyFingerprintCmd+echoMarker("FP-1"), "FP-1", 60*time.Second)
	before := fingerprint(t, out)
	ws.Close()
	tunnel.Close()

	resp := a.do(t, http.MethodPost, "/v1/machines/"+id+"/stop", api.StopRequest{Mode: api.StopModePoweroff})
	resp.Body.Close()
	a.waitState(t, id, api.StateStopped, 2*time.Minute)
	a.ensure(t, id)
	a.waitState(t, id, api.StateRunning, bootTimeout)

	// Wait for sshd again before asking it anything. `running` means the GUEST
	// container is ready, deliberately — a broken sshd must not cost a user
	// their terminal — so a terminal opens while sshd may still be starting.
	// Before this wait the fingerprint read raced it and ssh-keyscan returned
	// nothing, which reached ssh-keygen as "(stdin) is not a public key file"
	// and failed the run on main. The first fingerprint never raced because a
	// successful key login had already proved sshd was up.
	waitForSSHBanner(t, a, id, 90*time.Second)

	ws2, tunnel2 := a.terminal(t, id, "ssh-after-restart")
	defer tunnel2.Close()
	defer ws2.Close()
	out = runInGuest(t, ws2, hostKeyFingerprintCmd+echoMarker("FP-2"), "FP-2", 60*time.Second)
	if after := fingerprint(t, out); after != before {
		t.Errorf("host key changed across a restart (%s -> %s); every reconnect would warn the user", before, after)
	}
}

// waitForSSHBanner dials the machine's ssh port until sshd answers, and returns
// what it said. Both failure modes are retried and distinguished in the final
// message: the driver refusing the dial (sshd not ready yet) and the dial
// succeeding but the guest's forward closing it (sshd not listening).
func waitForSSHBanner(t *testing.T, a *agent, id string, timeout time.Duration) string {
	t.Helper()
	deadline := time.Now().Add(timeout)
	var last string
	for time.Now().Before(deadline) {
		conn, err := a.tryDialGuest(id, api.GuestSSHPort)
		if err != nil {
			last = "dial refused: " + err.Error()
			time.Sleep(2 * time.Second)
			continue
		}
		_ = conn.SetDeadline(time.Now().Add(15 * time.Second))
		buf := make([]byte, 64)
		n, err := conn.Read(buf)
		conn.Close()
		if n > 0 {
			return string(buf[:n])
		}
		last = fmt.Sprintf("read: %v", err)
		time.Sleep(2 * time.Second)
	}
	t.Fatalf("sshd never answered on guest port %d within %s (last: %s)", api.GuestSSHPort, timeout, last)
	return ""
}

// hostKeyFingerprintCmd prints the fingerprint of the host key sshd PRESENTS,
// asked over the protocol rather than read off the volume. Two reasons, and the
// first is that reading the file does not work: the host key directory is
// root-only (private keys live in it) and a session runs as the unprivileged
// user, so ssh-keygen -lf answers "Permission denied". The second is that this
// is the better assertion anyway — what a client pins is the key sshd offers,
// not a file that happens to sit next to it.
//
// The FP: tag is concatenated by awk at run time so it never appears literally
// in the command. Same reason echoMarker splits its marker: a PTY echoes what is
// typed into it, so a command containing its own tag is matched against the echo
// rather than the output, and the assertion compares the command with itself.
// (It did, on the first run of this test: "before" and "after" were both a
// fragment of the awk program.)
const hostKeyFingerprintCmd = `ssh-keyscan -t ed25519 127.0.0.1 2>/dev/null | ssh-keygen -lf - | awk '{print "F" "P:" $2}'; `

// fingerprint pulls the tagged fingerprint out of a PTY buffer. It insists on a
// SHA256: value and fails the test otherwise, so no other line — an echo, a
// prompt, an error, or ssh-keygen complaining that its input was empty — can be
// mistaken for one and make the before/after comparison trivially true.
func fingerprint(t *testing.T, out string) string {
	t.Helper()
	for _, line := range strings.Split(out, "\n") {
		i := strings.Index(line, "FP:")
		if i < 0 {
			continue
		}
		if fp := strings.TrimSpace(line[i+len("FP:"):]); strings.HasPrefix(fp, "SHA256:") {
			return fp
		}
	}
	t.Fatalf("no host key fingerprint in guest output: %q", tail(out))
	return ""
}

// TestKindCodeServer proves the web forward against a real pod: the guest agent
// starts code-server lazily on the first connection to the web port, and the
// tunnel carries plain HTTP to it. Nothing here is Kubernetes-specific except
// the thing that has never been tested on this backend — that a lazily-started,
// heavyweight child process inside a machine POD is reachable the same way it is
// inside a microVM.
func TestKindCodeServer(t *testing.T) {
	a := newAgent(t)
	const id = "e2e0kind-0000-4000-8000-000000000006"
	a.cleanup(t, id)

	a.ensure(t, id)
	a.waitState(t, id, api.StateRunning, bootTimeout)

	// code-server is started on demand and takes a while the first time (it
	// unpacks its own extensions), so this retries rather than assuming the
	// first connection is answered.
	deadline := time.Now().Add(3 * time.Minute)
	var last string
	for time.Now().Before(deadline) {
		status, body := httpOverTunnel(t, a, id, api.GuestWebPort)
		last = status + " " + body
		// 302 to /login is what an unauthenticated code-server answers with;
		// 200 is what it serves when auth is off. Either proves it is there.
		if strings.Contains(status, " 200") || strings.Contains(status, " 302") {
			return
		}
		time.Sleep(5 * time.Second)
	}
	t.Fatalf("code-server never answered through the web forward; last response: %q", tail(last))
}

// httpOverTunnel sends one HTTP/1.0 request to a guest port and returns the
// status line and body. HTTP/1.0 so the guest closes the connection and the read
// terminates without parsing content-length.
func httpOverTunnel(t *testing.T, a *agent, id string, port uint32) (string, string) {
	t.Helper()
	conn := a.dialGuest(t, id, port)
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(30 * time.Second))
	if _, err := conn.Write([]byte("GET / HTTP/1.0\r\nHost: guest\r\n\r\n")); err != nil {
		return "", ""
	}
	raw, _ := io.ReadAll(conn)
	text := string(raw)
	status, body, _ := strings.Cut(text, "\r\n")
	return status, body
}

// TestKindCapacity checks the synthesized cluster capacity is derived from the
// real node list rather than a configured constant, and that a running machine
// shows up as used.
func TestKindCapacity(t *testing.T) {
	a := newAgent(t)
	const id = "e2e0kind-0000-4000-8000-000000000003"
	a.cleanup(t, id)

	a.ensure(t, id)
	a.waitState(t, id, api.StateRunning, bootTimeout)

	resp := a.do(t, http.MethodGet, "/v1/capacity", nil)
	defer resp.Body.Close()
	var cap api.CapacityResponse
	if err := json.NewDecoder(resp.Body).Decode(&cap); err != nil {
		t.Fatal(err)
	}
	if cap.TotalVcpus <= 0 || cap.TotalMemMiB <= 0 {
		t.Errorf("cluster reports no capacity: %+v — the ClusterRole may not grant nodes list", cap)
	}
	if cap.UsedVcpus < 1 || cap.UsedMemMiB < 1024 {
		t.Errorf("used = %d vcpus / %d MiB, want at least the one running machine's 1 / 1024",
			cap.UsedVcpus, cap.UsedMemMiB)
	}
	if cap.UsedDiskMiB < 1024 {
		t.Errorf("used disk = %d MiB, want at least the machine's PVC", cap.UsedDiskMiB)
	}
}

// TestKindListAndReattach checks the driver finds machines it did not create in
// this process — the property that makes Reattach a list rather than a recovery,
// and the reason a cluster-agent restart does not lose the fleet.
func TestKindListAndReattach(t *testing.T) {
	a := newAgent(t)
	const id = "e2e0kind-0000-4000-8000-000000000004"
	a.cleanup(t, id)

	a.ensure(t, id)
	a.waitState(t, id, api.StateRunning, bootTimeout)

	resp := a.do(t, http.MethodGet, "/v1/machines", nil)
	defer resp.Body.Close()
	var list api.ListResponse
	if err := json.NewDecoder(resp.Body).Decode(&list); err != nil {
		t.Fatal(err)
	}
	for _, m := range list.Machines {
		if m.MachineID == id {
			if m.State != api.StateRunning {
				t.Errorf("List reports %s as %q, want running", id, m.State)
			}
			return
		}
	}
	t.Errorf("List omitted machine %s (got %d machines)", id, len(list.Machines))
}
