//go:build kind_e2e

// This file is behind the `kind_e2e` build tag: it needs a live cluster-agent
// backed by a real Kubernetes API server, which `deploy/kubernetes/e2e-kind.sh`
// provides. It is excluded from `go test ./...` and from the ordinary CI job.
//
// Everything else in this package tests the driver against a fake clientset,
// which cannot answer the questions that actually matter for this backend: does
// a pod schedule, does a PVC bind and survive a stop, does an image pull, does
// the kubelet's readiness probe survive the NetworkPolicy, can the cluster-agent
// really open a TCP connection to a machine's pod IP, and is the RBAC in
// deploy/kubernetes/base/rbac.yaml actually sufficient. This test asks all of
// them, through the same HTTP contract the control plane uses — the agent is a
// black box here, exactly as it is to the control plane.
package kubernetes_test

